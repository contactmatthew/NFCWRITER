package com.nfcwriter.app.nfc

import android.nfc.Tag
import android.nfc.tech.NfcA
import java.io.IOException
import java.security.SecureRandom

/** Exact NTAG213/215/216 variants from NXP data sheet NTAG213_215_216 rev. 3.2. */
enum class Ntag21xVariant(
    val storageSizeByte: Int,
    val configPage: Int,
    val accessPage: Int,
    val passwordPage: Int,
    val packPage: Int,
    val lastPage: Int,
) {
    NTAG213(0x0F, 0x29, 0x2A, 0x2B, 0x2C, 0x2C),
    NTAG215(0x11, 0x83, 0x84, 0x85, 0x86, 0x86),
    NTAG216(0x13, 0xE3, 0xE4, 0xE5, 0xE6, 0xE6);

    companion object {
        fun fromGetVersion(response: ByteArray): Ntag21xVariant? {
            if (response.size != 8) return null
            if (response[0].u() != 0x00 || response[1].u() != 0x04 ||
                response[2].u() != 0x04 || response[3].u() != 0x02 ||
                response[4].u() != 0x01 || response[5].u() != 0x00 ||
                response[7].u() != 0x03
            ) return null
            return entries.firstOrNull { it.storageSizeByte == response[6].u() }
        }
    }
}

data class NtagCredential(val password: ByteArray, val pack: ByteArray) {
    init {
        require(password.size == 4) { "NTAG21x password must be exactly 4 bytes." }
        require(pack.size == 2) { "NTAG21x PACK must be exactly 2 bytes." }
    }
    fun encoded(): ByteArray = password + pack
    companion object {
        fun decode(bytes: ByteArray): NtagCredential {
            require(bytes.size == 6) { "Invalid managed NTAG21x credential." }
            return NtagCredential(bytes.copyOfRange(0, 4), bytes.copyOfRange(4, 6))
        }

        /** Parses exactly 4 PWD bytes followed by 2 PACK bytes; no transformation is applied. */
        fun fromHex(value: String): NtagCredential {
            val normalized = value.trim().replace(" ", "").replace(":", "").replace("-", "")
            require(normalized.length == 12 && normalized.all { it.isDigit() || it.lowercaseChar() in 'a'..'f' }) {
                "Enter exactly 12 hexadecimal characters: 8 for PWD followed by 4 for PACK."
            }
            val bytes = ByteArray(6) { index -> normalized.substring(index * 2, index * 2 + 2).toInt(16).toByte() }
            return decode(bytes).also { bytes.fill(0) }
        }
    }
}

sealed interface ProtectionRequest {
    data object None : ProtectionRequest
    data object AutoGenerated : ProtectionRequest
    data class Custom(val credential: NtagCredential) : ProtectionRequest
}

object NtagCredentialGenerator {
    fun generate(random: SecureRandom = SecureRandom()): NtagCredential {
        val bytes = ByteArray(6).also(random::nextBytes)
        return NtagCredential(bytes.copyOfRange(0, 4), bytes.copyOfRange(4, 6)).also { bytes.fill(0) }
    }
}

enum class PhysicalSecurityState { UNPROTECTED, PROTECTED, UNAVAILABLE, UNKNOWN }

data class NtagSecurityInspection(
    val state: PhysicalSecurityState,
    val variant: Ntag21xVariant? = null,
    val auth0: Int? = null,
    val writeOnlyProtection: Boolean = false,
    val configurationLocked: Boolean = false,
    val reason: String? = null,
)

/**
 * The only class allowed to issue NTAG21x-specific raw commands.
 *
 * It fails closed unless GET_VERSION exactly matches an NXP NTAG213/215/216 response. It never
 * sets CFGLCK, lock bits, read protection, or a finite AUTHLIM. Reads therefore remain public.
 */
class Ntag21xManager {
    fun inspect(tag: Tag): NtagSecurityInspection {
        val tech = NfcA.get(tag) ?: return NtagSecurityInspection(
            PhysicalSecurityState.UNAVAILABLE,
            reason = "This tag does not expose NFC-A commands required for managed protection.",
        )
        tech.connect()
        return try {
            val variant = detectConnected(tech) ?: return NtagSecurityInspection(
                PhysicalSecurityState.UNAVAILABLE,
                reason = "The exact chip is not a verified NTAG213, NTAG215, or NTAG216.",
            )
            inspectConnected(tech, variant)
        } catch (error: Exception) {
            NtagSecurityInspection(PhysicalSecurityState.UNKNOWN, reason = safeIoMessage(error))
        } finally {
            runCatching { tech.close() }
        }
    }

    fun authenticate(tag: Tag, credential: NtagCredential): NtagSecurityInspection {
        val tech = connectSupported(tag)
        return try {
            val variant = requireNotNull(detectConnected(tech)) { "The tag is not an exact supported NTAG21x variant." }
            authenticateConnected(tech, credential)
            inspectConnected(tech, variant)
        } finally { runCatching { tech.close() } }
    }

    /**
     * Rewrites a TapTag-formatted Type 2 NDEF message without dropping the authenticated NFC-A
     * session. Switching from NfcA to Android's Ndef technology after PWD_AUTH resets auth on
     * some phones/tags, so protected writes must stay on this connection.
     */
    fun writeAuthenticatedNdef(tag: Tag, credential: NtagCredential, ndefMessage: ByteArray) {
        val tech = connectSupported(tag)
        try {
            val variant = requireNotNull(detectConnected(tech)) { "The tag is not an exact supported NTAG21x variant." }
            authenticateConnected(tech, credential)
            val existingFirstPage = readFourPages(tech, FIRST_NDEF_PAGE).copyOfRange(0, 4)
            require(existingFirstPage[0].u() == NDEF_TLV) {
                "Protected rewrite stopped safely: this tag's Type 2 memory layout is not a TapTag-compatible NDEF TLV."
            }
            val tlv = encodeType2NdefTlv(ndefMessage)
            val lastPage = FIRST_NDEF_PAGE + (tlv.size / PAGE_SIZE) - 1
            require(lastPage <= variant.configPage - 2) { "The encoded NDEF message exceeds this NTAG21x user-memory area." }

            // Publish an empty NDEF first. If communication is interrupted, readers see an empty
            // record rather than a partially updated message. Page 4 is committed last.
            writePage(tech, FIRST_NDEF_PAGE, byteArrayOf(NDEF_TLV.toByte(), 0, TERMINATOR_TLV.toByte(), 0))
            for (offset in PAGE_SIZE until tlv.size step PAGE_SIZE) {
                writePage(tech, FIRST_NDEF_PAGE + offset / PAGE_SIZE, tlv.copyOfRange(offset, offset + PAGE_SIZE))
            }
            writePage(tech, FIRST_NDEF_PAGE, tlv.copyOfRange(0, PAGE_SIZE))
        } catch (error: IOException) {
            throw IOException("NFC connection was interrupted during authenticated rewrite. Keep the tag steady and try again.", error)
        } finally {
            runCatching { tech.close() }
        }
    }

    fun enableWriteProtection(tag: Tag, credential: NtagCredential): NtagSecurityInspection {
        val tech = connectSupported(tag)
        return try {
            val variant = requireNotNull(detectConnected(tech)) { "The tag is not an exact supported NTAG21x variant." }
            val before = inspectConnected(tech, variant)
            require(before.state != PhysicalSecurityState.PROTECTED) { "This NTAG21x is already protected." }
            require(!before.configurationLocked) { "The NTAG21x security configuration is permanently locked." }

            writePage(tech, variant.passwordPage, credential.password)
            writePage(tech, variant.packPage, credential.pack + byteArrayOf(0, 0))

            val config = readFourPages(tech, variant.configPage)
            val access = config.copyOfRange(4, 8)
            // PROT=0 keeps reads public; CFGLCK and AUTHLIM remain disabled.
            access[0] = (access[0].u() and 0x38).toByte()
            access[1] = 0
            access[2] = 0
            access[3] = 0
            writePage(tech, variant.accessPage, access)

            val cfg0 = config.copyOfRange(0, 4)
            cfg0[3] = FIRST_NDEF_PAGE.toByte()
            writePage(tech, variant.configPage, cfg0)

            authenticateConnected(tech, credential)
            inspectConnected(tech, variant).also {
                require(it.state == PhysicalSecurityState.PROTECTED && it.writeOnlyProtection && it.auth0 == FIRST_NDEF_PAGE) {
                    "Protection configuration could not be verified."
                }
            }
        } finally { runCatching { tech.close() } }
    }

    fun removeWriteProtection(tag: Tag, credential: NtagCredential): NtagSecurityInspection {
        val tech = connectSupported(tag)
        return try {
            val variant = requireNotNull(detectConnected(tech)) { "The tag is not an exact supported NTAG21x variant." }
            val before = inspectConnected(tech, variant)
            require(before.state == PhysicalSecurityState.PROTECTED) { "This NTAG21x is not currently protected." }
            authenticateConnected(tech, credential)
            val config = readFourPages(tech, variant.configPage)
            val cfg0 = config.copyOfRange(0, 4).also { it[3] = 0xFF.toByte() }
            writePage(tech, variant.configPage, cfg0)
            inspectConnected(tech, variant).also {
                require(it.state == PhysicalSecurityState.UNPROTECTED) { "Protection removal could not be verified." }
            }
        } finally { runCatching { tech.close() } }
    }

    private fun connectSupported(tag: Tag): NfcA = requireNotNull(NfcA.get(tag)) {
        "This tag does not support the NFC-A commands required for managed protection."
    }.also { it.connect() }

    private fun detectConnected(tech: NfcA): Ntag21xVariant? =
        Ntag21xVariant.fromGetVersion(tech.transceive(byteArrayOf(GET_VERSION.toByte())))

    private fun inspectConnected(tech: NfcA, variant: Ntag21xVariant): NtagSecurityInspection {
        val pages = readFourPages(tech, variant.configPage)
        val auth0 = pages[3].u()
        val access = pages[4].u()
        val protected = auth0 <= variant.lastPage
        val readProtected = access and 0x80 != 0
        return NtagSecurityInspection(
            state = if (protected) PhysicalSecurityState.PROTECTED else PhysicalSecurityState.UNPROTECTED,
            variant = variant,
            auth0 = auth0,
            writeOnlyProtection = protected && !readProtected,
            configurationLocked = access and 0x40 != 0,
            reason = if (protected && readProtected) "This tag requires authentication for reading and does not match TapTag's public-read policy." else null,
        )
    }

    private fun authenticateConnected(tech: NfcA, credential: NtagCredential) {
        val response = tech.transceive(byteArrayOf(PWD_AUTH.toByte()) + credential.password)
        require(response.size >= 2 && response[0] == credential.pack[0] && response[1] == credential.pack[1]) {
            "NFC authentication failed. The managed credential was rejected."
        }
    }

    private fun readFourPages(tech: NfcA, startPage: Int): ByteArray =
        tech.transceive(byteArrayOf(READ.toByte(), startPage.toByte())).also {
            require(it.size == 16) { "Unexpected NTAG21x READ response." }
        }

    private fun writePage(tech: NfcA, page: Int, data: ByteArray) {
        require(data.size == 4)
        val response = tech.transceive(byteArrayOf(WRITE.toByte(), page.toByte()) + data)
        require(response.size == 1 && response[0].u() == ACK) { "The NTAG21x rejected a security configuration write." }
    }

    private fun safeIoMessage(error: Exception): String = when (error) {
        is IOException -> "NFC communication was interrupted while checking chip security."
        else -> error.message ?: "Unable to inspect chip security."
    }

    private companion object {
        const val GET_VERSION = 0x60
        const val READ = 0x30
        const val WRITE = 0xA2
        const val PWD_AUTH = 0x1B
        const val ACK = 0x0A
        const val FIRST_NDEF_PAGE = 0x04
        const val PAGE_SIZE = 4
        const val NDEF_TLV = 0x03
        const val TERMINATOR_TLV = 0xFE
    }
}

internal fun encodeType2NdefTlv(message: ByteArray): ByteArray {
    require(message.size <= 0xFFFF) { "NDEF message is too large for a Type 2 Tag TLV." }
    val header = if (message.size < 0xFF) {
        byteArrayOf(0x03, message.size.toByte())
    } else {
        byteArrayOf(0x03, 0xFF.toByte(), (message.size ushr 8).toByte(), message.size.toByte())
    }
    val unpadded = header + message + byteArrayOf(0xFE.toByte())
    val paddedSize = ((unpadded.size + 3) / 4) * 4
    return unpadded.copyOf(paddedSize)
}

private fun Byte.u(): Int = toInt() and 0xFF
